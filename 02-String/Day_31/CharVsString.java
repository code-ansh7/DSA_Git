public class CharVsString {

    public static void main(String[] args) {

        // Character stores only one character
        char grade = 'A';

        // String stores a sequence (collection) of characters
        String name = "Ansh";

        System.out.println("Character : " + grade);
        System.out.println("String    : " + name);

        System.out.println();

        System.out.println("'A' is a Character because it is enclosed in single quotes.");
        System.out.println("\"Ansh\" is a String because it is enclosed in double quotes.");
    }
}